#!/usr/bin/env node
/**
 * `EXT-16` lint half — regenerates the "allowed-tools enforceability" matrix inside
 * `docs/skills-portability.md`, between the `<!-- GENERATED:skills-lint:start -->` /
 * `<!-- GENERATED:skills-lint:end -->` markers. Semi-generated per this item's task text ("the
 * 20-row skill portability matrix ... semi-generated rather than hand-maintained"): this script
 * is the generator, the markers are the seam, and everything outside them (the hand-authored
 * layout/sanitation prose from `W1-CONTENT`, which this item does not own) is left untouched.
 *
 * Deliberately plain JS with its own tiny frontmatter reader, not an import of
 * `extensions/skills-lint.ts` — this script has to run standalone from `docs/` regeneration
 * tooling without a live PI process or `--experimental-strip-types`, the same reason
 * `extensions/skills-lint.ts`'s logic is duplicated here in miniature rather than shared. If the
 * two ever drift, `test/skills-lint.test.ts`'s fixture-based assertions on
 * `extensions/skills-lint.ts` are the source of truth for the *runtime* warning; this script
 * only needs to agree on what "declares allowed-tools" means.
 *
 * Usage: `node scripts/gen-skills-lint-matrix.mjs` (writes docs/skills-portability.md in place).
 *        `node scripts/gen-skills-lint-matrix.mjs --check` (exit 1 if regenerating would change
 *        the file — for a CI/verify.sh staleness gate; does not write).
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SKILL_ROOTS = ["skills"];
const DOC_PATH = join(REPO_ROOT, "docs", "skills-portability.md");
const START = "<!-- GENERATED:skills-lint:start -->";
const END = "<!-- GENERATED:skills-lint:end -->";

function parseAllowedTools(raw) {
  if (Array.isArray(raw)) {
    return raw.filter((v) => typeof v === "string").map((v) => v.trim()).filter(Boolean);
  }
  if (typeof raw === "string") {
    return raw.split(",").map((v) => v.trim()).filter(Boolean);
  }
  return [];
}

function readFrontmatter(text) {
  if (!text.startsWith("---")) return {};
  const end = text.indexOf("\n---", 3);
  if (end === -1) return {};
  const yamlString = text.slice(4, end);
  return parseYaml(yamlString) ?? {};
}

export function collectRows(root) {
  const rows = [];
  for (const tier of SKILL_ROOTS) {
    const dir = join(root, tier);
    let entries;
    try {
      entries = readdirSync(dir);
    } catch {
      continue;
    }
    for (const entry of entries.toSorted()) {
      const skillMdPath = join(dir, entry, "SKILL.md");
      try {
        if (!statSync(skillMdPath).isFile()) continue;
      } catch {
        continue;
      }
      const raw = readFileSync(skillMdPath, "utf8");
      let frontmatter;
      try {
        frontmatter = readFrontmatter(raw);
      } catch (err) {
        // Real, independently-observed case: a SKILL.md whose unquoted `description:` contains a
        // colon throws YAMLParseError in PI's own parseFrontmatter too (verified against the
        // pinned package — see extensions/skills-lint.ts's docstring). One bad file must not abort
        // the whole matrix.
        rows.push({ name: entry, tier, declares: false, allowedTools: [], parseError: err.message.split("\n")[0] });
        continue;
      }
      const allowedTools = parseAllowedTools(frontmatter["allowed-tools"]);
      rows.push({
        name: typeof frontmatter.name === "string" ? frontmatter.name : entry,
        tier,
        declares: allowedTools.length > 0,
        allowedTools,
      });
    }
  }
  return rows;
}

export function renderTable(rows) {
  const lines = [
    START,
    "<!-- Generated by `node scripts/gen-skills-lint-matrix.mjs` — do not hand-edit this block. -->",
    "",
    "### Allowed-tools enforceability (generated, `EXT-16` lint half)",
    "",
    "PI's skill loader (`dist/core/skills.js`, pinned `@earendil-works/pi-coding-agent` 0.84.0) parses",
    "exactly three frontmatter fields: `name`, `description`, `disable-model-invocation`. `allowed-tools`",
    "is read by nothing in the package. **Every row below marked \"declared\" is a warning, not a",
    "guarantee** — `extensions/skills-lint.ts` surfaces it once per session, and this table is the same",
    "fact laid out per skill, regenerated from the tree, not hand-maintained.",
    "",
    `Total: ${rows.length} skills scanned (\`skills/\` — \`skill-bundles/\` is excluded, same as the`,
    "layout matrix above: a bundle's members are never addressed by name directly).",
    "",
    "| Skill | Tier | allowed-tools declared | Enforced by PI |",
    "|---|---|---|---|",
  ];
  for (const row of rows) {
    if (row.parseError) {
      lines.push(`| \`${row.name}\` | \`${row.tier}\` | **frontmatter fails to parse** (${row.parseError}) | n/a |`);
      continue;
    }
    const declared = row.declares ? `yes (${row.allowedTools.join(", ")})` : "no";
    const enforced = row.declares ? "**no** — advisory only" : "n/a";
    lines.push(`| \`${row.name}\` | \`${row.tier}\` | ${declared} | ${enforced} |`);
  }
  lines.push("", END);
  return lines.join("\n");
}

function spliceIntoDoc(existing, generatedBlock) {
  const startIdx = existing.indexOf(START);
  const endIdx = existing.indexOf(END);
  if (startIdx === -1 || endIdx === -1) {
    // First run: append with a blank-line separator, after the existing hand-authored content.
    return `${existing.trimEnd()}\n\n${generatedBlock}\n`;
  }
  const before = existing.slice(0, startIdx);
  const after = existing.slice(endIdx + END.length);
  return `${before}${generatedBlock}${after}`;
}

function main() {
  const rows = collectRows(REPO_ROOT);
  const generatedBlock = renderTable(rows);
  const existing = readFileSync(DOC_PATH, "utf8");
  const next = spliceIntoDoc(existing, generatedBlock);

  const checkOnly = process.argv.includes("--check");
  if (checkOnly) {
    if (next !== existing) {
      process.stderr.write(
        `docs/skills-portability.md is stale — run \`node scripts/gen-skills-lint-matrix.mjs\` to regenerate.\n`,
      );
      process.exit(1);
    }
    process.stdout.write("docs/skills-portability.md matches the generated matrix.\n");
    return;
  }

  writeFileSync(DOC_PATH, next, "utf8");
  process.stdout.write(`docs/skills-portability.md: wrote ${rows.length}-row generated matrix.\n`);
}

main();
