/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

export const id = "PC-28";
export const title = "Routing prose in AGENTS.md/SYSTEM.md/subagent-tool-description.md agrees with config/routing.default.json and config/dispatch.json";

// THE FAILURE MODE THIS RULE CLOSES
// ----------------------------------
// `config/routing.default.json` and `config/dispatch.json` are the only authority for which tier
// is the default and what each tier resolves to. A doc that restates one of those facts in prose —
// "the default tier is X", "model Y runs at thinking level Z" — is correct on the day it is
// written and silently wrong the day either config file changes under it, because nothing connects
// the two. Left alone, that is worse than no restatement at all: a doc that is a pinned context
// source (re-injected after every compaction, in configurations that use one) outranks the config
// it now contradicts, every time it is re-read.
//
// This rule reads the two config files as the ONLY authority and fails when prose disagrees with
// them. It never hardcodes a tier name, a model id or a thinking level — those are exactly the
// values an install changes, and a rule that hardcodes today's tier name goes stale the same way
// the prose it is meant to catch does.
//
// WHAT IT DOES NOT DO, ON PURPOSE
// --------------------------------
// It does not flag a tier name or a model id mentioned on its own — "`light` for a mechanical
// one-liner" names a real tier and asserts nothing checkable, and a rule that fired on every
// mention would be suppressed within a week. It only fires on two SPECIFIC, checkable claims:
//
//   1. A model pinned to a thinking level — `` `provider/id:level` `` or
//      `` `provider/id` at `thinkingLevel: level` `` — where the level disagrees with what
//      `routing.default.json` declares for the tier that owns that model.
//   2. A "defaults to the `<tier>` tier" claim, where `<tier>` is a real tier name that disagrees
//      with `dispatch.json`'s `defaultTier`.
//
// WHICH ROUTING FILE
// -------------------
// `config/routing.json` is generated by `scripts/install.sh` from the provider fragments this
// install picked and is git-ignored — it does not exist until an install has actually run. Same
// fallback every other routing rule in this file uses (pc-01, pc-02, pc-04, pc-08, pc-20): prefer
// the live, operator-chosen `routing.json` when an install has happened, so prose is checked
// against what is ACTUALLY running; fall back to the template `routing.default.json` — the file
// every fork commits — before that, so a clone with no install yet is still checked against
// something.
//
// TOLERANCES
// ----------
// Neither routing file present, or the one found fails to parse as the expected shape: nothing to
// check against, so no findings. A missing or unparseable `config/dispatch.json` only disables
// claim (2) above; claim (1) needs nothing from it. A target doc that does not exist is skipped,
// not an error.

const DISPATCH = "config/dispatch.json";
const TARGET_DOCS = ["AGENTS.md", "SYSTEM.md", "config/subagent-tool-description.md"];

// Matched against each line with backticks stripped first (see `dropBackticks` below), so these
// patterns never have to guess where Markdown put the inline-code delimiters — `` `model:
// "github-copilot/claude-opus-5:high"` `` and `` `github-copilot/claude-opus-5` at `thinkingLevel:
// high` `` both read the same way once the backticks are gone. Narrowness comes from the
// exact-match lookup against `tierByModel` below, not from the punctuation around the match.
const MODEL_ID = "[A-Za-z][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*";
const SUFFIX_RE = new RegExp("(" + MODEL_ID + "):([A-Za-z]+)", "g");
const PROSE_RE = new RegExp("(" + MODEL_ID + ")\\s+at\\s+thinkingLevel:\\s*\"?([A-Za-z]+)\"?", "g");
const DEFAULT_TIER_RE = /defaults? to (?:the )?([A-Za-z][A-Za-z0-9_-]*) tier/gi;

/** @param {string} text @returns {string} */
function dropBackticks(text) {
  return text.replace(/`/g, "");
}

/**
 * `{ bareModelId: { tier, thinkingLevel } }` for every tier `routing.default.json` declares.
 * `thinkingLevel` is `undefined` when the tier declares none — a doc that pins one anyway is
 * still a disagreement with the config, not a pass.
 *
 * @param {Record<string, { model?: unknown, thinkingLevel?: unknown }>} tiers
 * @returns {Map<string, { tier: string, thinkingLevel: string | undefined }>}
 */
function modelsByTier(tiers) {
  const map = new Map();
  for (const [tier, row] of Object.entries(tiers)) {
    if (!row || typeof row.model !== "string") continue;
    map.set(row.model, { tier, thinkingLevel: typeof row.thinkingLevel === "string" ? row.thinkingLevel : undefined });
  }
  return map;
}

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  /** @type {Finding[]} */
  const findings = [];
  const ROUTING = ctx.exists("config/routing.json") ? "config/routing.json" : "config/routing.default.json";
  if (!ctx.exists(ROUTING)) return findings;

  let routing;
  try {
    routing = ctx.readJSON(ROUTING);
  } catch (err) {
    return [{ rule: id, file: ROUTING, message: String(err.message ?? err) }];
  }
  const tiers = routing && typeof routing === "object" ? routing.tiers : undefined;
  if (!tiers || typeof tiers !== "object") return findings;

  const tierByModel = modelsByTier(tiers);
  const knownTiers = new Set(Object.keys(tiers));

  let defaultTier;
  if (ctx.exists(DISPATCH)) {
    try {
      const dispatch = ctx.readJSON(DISPATCH);
      if (dispatch && typeof dispatch === "object" && typeof dispatch.defaultTier === "string") {
        defaultTier = dispatch.defaultTier;
      }
    } catch {
      // Malformed dispatch.json is a different rule's problem; claim (1) below needs none of it.
    }
  }

  for (const doc of TARGET_DOCS) {
    if (!ctx.exists(doc)) continue;
    for (const { line, text: raw } of ctx.lines(doc)) {
      const text = dropBackticks(raw);
      for (const re of [SUFFIX_RE, PROSE_RE]) {
        re.lastIndex = 0;
        let m;
        while ((m = re.exec(text)) !== null) {
          const [, modelId, level] = m;
          const entry = tierByModel.get(modelId);
          if (!entry) continue; // not one of the config's tier models — out of scope
          if (entry.thinkingLevel === undefined) {
            findings.push({
              rule: id,
              file: doc,
              line,
              message: `pins "${modelId}" at thinkingLevel "${level}", but ${ROUTING}'s tier "${entry.tier}" declares no thinkingLevel for it — the doc asserts a level the config does not.`,
            });
          } else if (level !== entry.thinkingLevel) {
            findings.push({
              rule: id,
              file: doc,
              line,
              message: `pins "${modelId}" at thinkingLevel "${level}", but ${ROUTING}'s tier "${entry.tier}" declares thinkingLevel "${entry.thinkingLevel}" — update the doc or the config, whichever is stale.`,
            });
          }
        }
      }

      if (defaultTier !== undefined) {
        DEFAULT_TIER_RE.lastIndex = 0;
        let m;
        while ((m = DEFAULT_TIER_RE.exec(text)) !== null) {
          const tierName = m[1];
          if (!knownTiers.has(tierName)) continue; // not a real tier — some other kind of "default"
          if (tierName !== defaultTier) {
            findings.push({
              rule: id,
              file: doc,
              line,
              message: `asserts subagents default to the "${tierName}" tier, but config/dispatch.json's defaultTier is "${defaultTier}" — the prose is stale; point at the config instead of restating it.`,
            });
          }
        }
      }
    }
  }
  return findings;
}
