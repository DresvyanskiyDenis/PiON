/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

// `onProviderError.workingRoute.zeroTokenFallback` names a tier the harness hops the session to
// when a zero-token empty-response comes back (`extensions/credentials.ts`'s
// `handleZeroTokenEmpty`). This is the offline, config-shape half of
// `extensions/lib/provider-retry.ts`'s `resolveWorkingRouteTarget` — a typo'd or renamed tier there
// does not crash anything at runtime, it just makes every hop this session ever attempts decline
// and abort (the fallback "is not in this session's model registry", or "does not declare" a
// matching tier), silently in the sense that nobody sees it until a zero-token empty-response
// actually happens. This rule is the same "catch it at config-check time before deployment" job
// PC-02 and PC-20 already do for `tiers` and `path-defaults.json`'s `tier` — duplicated here rather
// than imported, for the same reason PC-20 duplicates instead of importing: pi-check has zero
// dependencies on this repo's own TypeScript.
//
// WHY THIS IS A WARNING AND NOT A FINDING
// ----------------------------------------
// A configured fallback that cannot resolve is a legal, loading tree — the hop simply declines and
// the failure aborts exactly as it did before the working-path hop existed, which is the same safe
// default `resolveWorkingRouteTarget` falls back to at runtime. Nothing here may fail a build over
// a config shape that only ever produces a graceful decline.
//
// SCOPE
// -----
// It checks EXISTENCE only, the same scope PC-20 draws for its own `tier` field, and it treats a
// name this file lists under `tiersUnbound` as its own, distinct case from a name declared nowhere
// at all: the former is a deliberate "this install has nothing to point that name at" (this repo's
// own `confidential` tier, unbound by default), the latter is typo-shaped. Whether the fallback is
// a genuinely different DEPLOYMENT from whatever is currently failing is a runtime question this
// rule cannot answer statically — the whole reason the hop targets a different provider rather than
// excluding a specific backing deployment is that the failing deployment is not knowable from
// config in the first place.

export const id = "PC-33";
export const title = "onProviderError.workingRoute.zeroTokenFallback resolves to a usable tier or literal model";
export const closes = [];

/** @param {unknown} value @returns {Record<string, unknown> | undefined} */
function plainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? /** @type {Record<string, unknown>} */ (value)
    : undefined;
}

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  // config/routing.json is generated by the installer and git-ignored, so before the first install
  // only the tracked template is on disk. Same fallback every other routing rule here uses.
  const REL = ctx.exists("config/routing.json") ? "config/routing.json" : "config/routing.default.json";
  if (!ctx.exists(REL)) return []; // PC-02's territory, not this rule's

  let routing;
  try {
    routing = ctx.readJSON(REL);
  } catch {
    return []; // an unreadable routing file is already PC-01/PC-02's finding
  }

  const parsed = plainObject(routing);
  const workingRoute = plainObject(plainObject(parsed?.onProviderError)?.workingRoute);
  if (workingRoute === undefined) return []; // not configured — the hop is simply off, not broken

  const fallback = workingRoute.zeroTokenFallback;
  if (fallback === undefined) return []; // same posture: an unset fallback is off, not a finding

  const warn = (message) => {
    const anchor = ctx.lines(REL).find((l) => typeof fallback !== "string" || l.text.includes(fallback));
    return [{ rule: id, file: REL, ...(anchor !== undefined ? { line: anchor.line } : {}), severity: "warn", message }];
  };

  if (typeof fallback !== "string" || fallback.length === 0) {
    return warn(`onProviderError.workingRoute.zeroTokenFallback must be a non-empty string naming a tier or provider/id, got ${JSON.stringify(fallback)}`);
  }
  if (fallback === "") {
    return []; // an explicit "" disables the hop outright — a legitimate, resolvable statement
  }
  if (fallback.includes("/")) {
    const [provider, modelId] = fallback.split("/", 2);
    if (!provider || !modelId) {
      return warn(`onProviderError.workingRoute.zeroTokenFallback "${fallback}" is not of the form provider/id`);
    }
    return []; // a literal provider/id resolves without consulting tiers at all
  }

  const unbound = plainObject(parsed?.tiersUnbound);
  if (unbound !== undefined && typeof unbound[fallback] === "string") {
    return warn(
      `onProviderError.workingRoute.zeroTokenFallback "${fallback}" names a tier this install leaves ` +
        `deliberately unbound (${unbound[fallback]}) — every zero-token-empty hop this session attempts ` +
        "will decline and abort until it is bound",
    );
  }

  const tiers = plainObject(parsed?.tiers) ?? {};
  if (!(fallback in tiers)) {
    return warn(
      `onProviderError.workingRoute.zeroTokenFallback "${fallback}" is not defined in this file's "tiers" ` +
        "— every zero-token-empty hop this session attempts will decline and abort",
    );
  }

  return [];
}
