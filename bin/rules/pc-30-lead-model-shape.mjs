/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

// PC-30 — a committed lead-model pin is well formed and points at a live tier.
//
// WHAT IT CHECKS
//
// `.pi/lead-model.json`, when the repo has one: the shape `extensions/lead-model/config.ts`
// enforces at run time, plus the one thing that file cannot check offline — that the tier it names
// still exists in the routing table.
//
// WHY THE TIER HALF IS THE POINT
//
// The shape half is a regression guard, restated in plain JavaScript the way PC-20 restates
// path-defaults' validator, because pi-check has no dependencies at all — including on this repo's
// own TypeScript. The tier half catches a real and silent failure: a tier renamed or deleted in the
// routing table leaves the pin file untouched and syntactically perfect, and the only symptom is
// one error notice at session start followed by a session that is no longer pinned to anything.
//
// A pin that has quietly stopped pinning is worse than no pin, because the documentation goes on
// saying the lead is held while it is not. Both files are committed, so the disagreement can be
// caught by a gate before it is discovered by a session.
//
// SCOPE
//
// This repo's own pin, only. Every other project's `.pi/lead-model.json` lives in that project's
// tree, and pi-check never reads outside the scanned repo. An absent pin file is the normal,
// unpinned state and is not a finding.

export const id = "PC-30";
export const title = "A committed .pi/lead-model.json is well-formed and names a live routing tier";
export const closes = [];

const PIN = ".pi/lead-model.json";
const MIN_REASON_LENGTH = 12;
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  if (!ctx.exists(PIN)) return [];

  /** @type {Finding[]} */
  const findings = [];
  const fail = (message) => findings.push({ rule: id, file: PIN, message });

  let pin;
  try {
    pin = ctx.readJSON(PIN);
  } catch (err) {
    fail(String(err.message ?? err));
    return findings;
  }
  if (pin === null || typeof pin !== "object" || Array.isArray(pin)) {
    fail("must be a JSON object");
    return findings;
  }

  if (pin.version !== 1) fail(`"version" must be 1, got ${JSON.stringify(pin.version)}`);
  if (typeof pin.since !== "string" || !ISO_DATE.test(pin.since)) {
    fail(`"since" must be a YYYY-MM-DD date, got ${JSON.stringify(pin.since)}`);
  }
  if (typeof pin.reason !== "string" || pin.reason.trim().length < MIN_REASON_LENGTH) {
    fail(`"reason" must say why this project is pinned, in at least ${MIN_REASON_LENGTH} characters`);
  }
  if (typeof pin.tier !== "string" || pin.tier.length === 0) {
    fail('"tier" must be a non-empty string naming a routing tier');
    return findings;
  }

  // config/routing.json is generated by the installer and git-ignored, so before the first install
  // only the tracked template is on disk. Same fallback every other routing rule here uses.
  const ROUTING = ctx.exists("config/routing.json") ? "config/routing.json" : "config/routing.default.json";
  if (!ctx.exists(ROUTING)) return findings; // PC-02's territory, not this rule's

  let routing;
  try {
    routing = ctx.readJSON(ROUTING);
  } catch {
    return findings; // PC-01 and PC-02 already report an unreadable routing table
  }
  const tiers = routing && typeof routing === "object" ? routing.tiers : undefined;
  const row = tiers && typeof tiers === "object" ? tiers[pin.tier] : undefined;
  if (row === undefined) {
    const known = tiers && typeof tiers === "object" ? Object.keys(tiers).join(", ") : "(none)";
    fail(
      `pins tier "${pin.tier}", which ${ROUTING} does not define. The pin would resolve to nothing ` +
        `and the project would silently stop being pinned. Known tiers: ${known}`,
    );
  }

  return findings;
}
