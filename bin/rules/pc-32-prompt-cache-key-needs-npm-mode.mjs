/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

export const id = "PC-32";
export const title = "compat.supportsPromptCacheKey is unpatchable under the default --mode binary install";

// WHY THIS IS A WARNING AND NOT A FINDING
// ----------------------------------------
// `compat.supportsPromptCacheKey: true` is a completely legal config/models.json entry. It parses,
// it loads, and answering "yes" in the litellm interview is exactly what writes it
// (config/providers/litellm.json). Nothing about such a tree is broken, so nothing here may fail a
// build over it.
//
// What it is, is inert on arrival, and — under the install mode PI defaults to — inert forever.
// docs/configuration/litellm.md already documents that `pi-ai` 0.84.4 ships no such condition: the
// flag only changes anything once the *runtime* is patched (`patch-package`, three lines in
// `dist/api/openai-completions.js`). Which copy of the runtime serves a turn depends on the install
// mode (docs/getting-started/install.md#the-pi-runtime-itself):
//   - `--mode npm`: a global package tree under `$(npm root -g)/@earendil-works` — `patch-package`
//     can reach it, so the flag is inert only until someone applies the patch.
//   - `--mode binary` (the default, and per docs/limitations.md a compiled Bun executable, not
//     Node): an unpacked release archive with no package tree at all — there is nothing for
//     `patch-package` to run against, so the flag cannot be made to do anything, ever, without
//     switching install modes.
// "Legal, loads, and buys nothing under the mode most installs run" is exactly PC-31's shape: a gate
// that failed a build over a judgement call like this gets switched off, and every real finding it
// also carries goes dark with it. This gets said once, in the run output, and the operator decides.
//
// WHAT IT DOES NOT CHECK, ON PURPOSE
// -----------------------------------
// It does not know which install mode THIS machine actually runs — bin/pi-check validates the
// committed config tree offline and never touches the filesystem outside it (see bin/pi-check's own
// header), so it cannot read `~/.local/share/pi-config/runtime/` or `$(npm root -g)`. It warns on
// the flag unconditionally, because `--mode binary` is the documented default and the unpatchable
// case; an operator on `--mode npm` who has actually applied the patch reads the warning and knows
// it does not apply to them.

/** @param {unknown} value @returns {Record<string, unknown> | undefined} */
function plainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? /** @type {Record<string, unknown>} */ (value)
    : undefined;
}

const REL_JSON = "config/models.json";
const REL_DEFAULT = "config/models.default.json";

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  // config/models.json is generated by the installer and git-ignored, so before the first install
  // only the tracked template is on disk. Same fallback every other models.json rule here uses.
  const REL = ctx.exists(REL_JSON) ? REL_JSON : REL_DEFAULT;
  if (!ctx.exists(REL)) return [];

  let models;
  try {
    models = ctx.readJSON(REL);
  } catch {
    return []; // an unreadable models file is already another rule's finding
  }

  const providers = plainObject(models)?.providers;
  if (!providers || typeof providers !== "object") return [];

  const fileLines = ctx.lines(REL);

  /** @type {Finding[]} */
  const findings = [];
  for (const [providerId, provider] of Object.entries(providers)) {
    const compat = plainObject(plainObject(provider)?.compat);
    if (compat?.supportsPromptCacheKey !== true) continue;

    // Line-addressed to the key that flipped this on, so the report points at where to type.
    const anchor = fileLines.find(({ text }) => text.includes('"supportsPromptCacheKey"'));

    findings.push({
      rule: id,
      file: REL,
      ...(anchor !== undefined ? { line: anchor.line } : {}),
      severity: "warn",
      message:
        `providers.${providerId}.compat.supportsPromptCacheKey is true, but the shipped pi-ai runtime ` +
        "reads no such flag — it is a patch, not a feature (docs/configuration/litellm.md#prompt-cache-keys-through-a-proxy). " +
        "Under --mode binary, PI's default install mode, there is no package tree to patch at all, so " +
        "the flag cannot be made to do anything without switching to --mode npm and applying the patch " +
        "yourself. See docs/limitations.md for the binary-mode gap.",
    });
  }
  return findings;
}
