/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

export const id = "PC-31";
export const title = 'The routing file retries "empty-response" without varying the request';

// WHY THIS IS A WARNING AND NOT A FINDING
// ----------------------------------------
// `onProviderError.retry.classes` containing `empty-response` with no `retry.onEmpty.strategy` is
// a completely legal configuration. It parses, it loads, `extensions/credentials.ts` honours it,
// and it is exactly what this repository shipped when `retry` first landed. Nothing about such a
// tree is broken, so nothing here may fail a build over it.
//
// What it is, is measurably pointless. On an audited session tree `empty-response` did not spread
// evenly across the configured providers: the overwhelming majority landed on a single gateway
// route, a couple on a second provider, and none at all on a third. The class correlates with the
// ROUTE, and at `temperature: 0` re-sending the same bytes to the same route is the retry variant
// with the lowest expected recovery rate of any option available. So the retry costs a round trip
// and a turn's worth of tokens and, by measurement, buys close to nothing.
//
// "Legal, loads, and buys nothing" is precisely the shape that must not be an error. A gate that
// fails a machine over a judgement call gets switched off, and every real finding it also carries
// goes silent with it. This gets said once, in the run output, and the operator decides.
//
// WHAT IT DOES NOT CHECK, ON PURPOSE
// -----------------------------------
// It says nothing about `network`, which is retried identically on purpose and correctly: DNS,
// TLS, proxy and 5xx are route-independent, so the original argument holds there untouched.
// It does not check `maxAttempts` — a `0` there is the documented opt-out and disables retrying
// entirely, so a missing strategy under it costs nothing and is not worth a line of output.
// It does not require `strategy: "vary"`; an explicit `"identical"` is a recorded decision, and
// this rule's whole job is to tell a decision apart from a default nobody read.

/** @param {unknown} value @returns {Record<string, unknown> | undefined} */
function plainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? /** @type {Record<string, unknown>} */ (value)
    : undefined;
}

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  // config/routing.json is generated by the installer and git-ignored, so before the first install
  // only the tracked template is on disk. Same fallback every other routing rule here uses.
  const REL = ctx.exists("config/routing.json") ? "config/routing.json" : "config/routing.default.json";
  if (!ctx.exists(REL)) return []; // PC-02's territory, not this rule's

  let routing;
  try {
    routing = ctx.readJSON(REL);
  } catch {
    return []; // an unreadable routing file is already PC-01/PC-02's finding
  }

  const block = plainObject(plainObject(routing)?.onProviderError);
  const retry = plainObject(block?.retry);
  if (retry === undefined) return [];
  if (!Array.isArray(retry.classes) || !retry.classes.includes("empty-response")) return [];
  // `maxAttempts: 0` is the opt-out: nothing is retried, so nothing is retried pointlessly.
  if (retry.maxAttempts === 0) return [];
  if (plainObject(retry.onEmpty)?.strategy !== undefined) return [];

  // Line-addressed to the key that would carry the answer, so the report points at where to type.
  const anchor = ctx.lines(REL).find(({ text }) => text.includes('"empty-response"'));

  return [
    {
      rule: id,
      file: REL,
      ...(anchor !== undefined ? { line: anchor.line } : {}),
      severity: "warn",
      message:
        'onProviderError.retry.classes retries "empty-response" but declares no retry.onEmpty.strategy. ' +
        "An identical retry is a no-op by measurement: the class correlates with the route, so the same " +
        'bytes to the same route recover least often. Set onEmpty.strategy to "vary" with a thinkingLevel, ' +
        'or to "identical" to record that the resend is deliberate. See docs/configuration/routing.md',
    },
  ];
}
