/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

export const id = "PC-14";
export const title = "PI_ALLOW_BROWSER_COOKIES and FEYNMAN_ALLOW_BROWSER_COOKIES are unset everywhere";
export const closes = ["REQ-PRV-12a"]; // this week's finding: pi-web-access's chrome-cookies.ts path

const VARS = ["PI_ALLOW_BROWSER_COOKIES", "FEYNMAN_ALLOW_BROWSER_COOKIES"];
const SETS_VAR = (name) => new RegExp(`^\\s*export\\s+${name}\\s*=\\s*\\S`);

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  /** @type {Finding[]} */
  const findings = [];
  const ENV_SH = "config/shell/pi-env.sh";
  if (ctx.exists(ENV_SH)) {
    for (const { line, text } of ctx.lines(ENV_SH)) {
      if (/^\s*#/.test(text)) continue;
      for (const name of VARS) {
        if (SETS_VAR(name).test(text)) {
          findings.push({ rule: id, file: ENV_SH, line, message: `${name} is exported — the browser-cookie credential path (pi-web-access's chrome-cookies.ts) must stay opt-in-per-invocation, never ambient` });
        }
      }
    }
  }

  // config/settings.json is generated by the installer and git-ignored; on a fresh clone only
  // the tracked config/settings.default.json exists. Checking whichever is present keeps this
  // rule meaningful before the first install instead of silently returning zero findings.
  const SETTINGS = ctx.exists("config/settings.json") ? "config/settings.json" : "config/settings.default.json";
  if (ctx.exists(SETTINGS)) {
    try {
      const settings = ctx.readJSON(SETTINGS);
      for (const name of VARS) {
        if (settings && typeof settings === "object" && name in settings) {
          findings.push({ rule: id, file: SETTINGS, message: `${name} key present in settings.json — must stay unset` });
        }
      }
    } catch (err) {
      findings.push({ rule: id, file: SETTINGS, message: String(err.message ?? err) });
    }
  }

  for (const name of VARS) {
    if (name in process.env) {
      findings.push({ rule: id, file: "(ambient environment)", message: `${name} is set in the environment running this check` });
    }
  }
  return findings;
}
