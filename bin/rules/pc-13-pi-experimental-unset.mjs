/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

export const id = "PC-13";
export const title = "PI_EXPERIMENTAL is not set in config/shell/pi-env.sh, config/settings.json, or the ambient env";
export const closes = ["REQ-PRV-56"];

const SETS_VAR = (name) => new RegExp(`^\\s*export\\s+${name}\\s*=\\s*\\S`);
const UNSETS_VAR = (name) => new RegExp(`^\\s*unset\\s+${name}\\b`);

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  /** @type {Finding[]} */
  const findings = [];
  const ENV_SH = "config/shell/pi-env.sh";
  if (ctx.exists(ENV_SH)) {
    let unset = false;
    for (const { line, text } of ctx.lines(ENV_SH)) {
      if (/^\s*#/.test(text)) continue;
      if (UNSETS_VAR("PI_EXPERIMENTAL").test(text)) unset = true;
      if (SETS_VAR("PI_EXPERIMENTAL").test(text)) {
        findings.push({ rule: id, file: ENV_SH, line, message: "PI_EXPERIMENTAL is exported — REQ-PRV-56 requires it to stay unset" });
      }
    }
    if (!unset) {
      findings.push({ rule: id, file: ENV_SH, message: 'PI_EXPERIMENTAL is not explicitly "unset" — REQ-PRV-56 requires the posture to be asserted, not merely absent' });
    }
  }

  // config/settings.json is generated by the installer and git-ignored; on a fresh clone only
  // the tracked config/settings.default.json exists. Checking whichever is present keeps this
  // rule meaningful before the first install instead of silently returning zero findings.
  const SETTINGS = ctx.exists("config/settings.json") ? "config/settings.json" : "config/settings.default.json";
  if (ctx.exists(SETTINGS)) {
    try {
      const settings = ctx.readJSON(SETTINGS);
      if (settings && typeof settings === "object" && "PI_EXPERIMENTAL" in settings) {
        findings.push({ rule: id, file: SETTINGS, message: "PI_EXPERIMENTAL key present in settings.json — REQ-PRV-56 requires it unset" });
      }
    } catch (err) {
      findings.push({ rule: id, file: SETTINGS, message: String(err.message ?? err) });
    }
  }

  if ("PI_EXPERIMENTAL" in process.env) {
    findings.push({ rule: id, file: "(ambient environment)", message: `PI_EXPERIMENTAL is set in the environment running this check ("${process.env.PI_EXPERIMENTAL}")` });
  }
  return findings;
}
