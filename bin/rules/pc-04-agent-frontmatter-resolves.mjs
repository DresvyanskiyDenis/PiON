/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */
import { parseFrontmatter } from "../lib/frontmatter.mjs";
import { PROVIDER_QUALIFIED } from "../lib/patterns.mjs";

export const id = "PC-04";
export const title = "Every agents/*.md frontmatter model/tier field resolves against config/routing.json";
export const closes = ["REQ-CTX-46", "REQ-PRV-12a"];

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  const files = ctx.listFiles({ dir: "agents", exts: [".md"] });
  if (files.length === 0) return [];

  /** @type {Finding[]} */
  const findings = [];

  /** @type {Set<string>} */
  let tierNames = new Set();
  // config/routing.json and config/models.json are generated by the installer and git-ignored.
  // Before the first install only the tracked *.default.json templates are on disk, and the rule
  // has to check those instead — otherwise `pi-check` on a fresh clone reports the repo's own
  // shipped defaults as broken, which is exactly backwards.
  const ROUTING = ctx.exists("config/routing.json") ? "config/routing.json" : "config/routing.default.json";
  if (ctx.exists(ROUTING)) {
    try {
      const routing = ctx.readJSON(ROUTING);
      const tiers = routing && typeof routing === "object" ? routing.tiers : undefined;
      if (tiers && typeof tiers === "object") tierNames = new Set(Object.keys(tiers));
    } catch {
      // PC-01/PC-02 already report a broken routing.json; don't double-report here.
    }
  }

  for (const file of files) {
    const text = ctx.readText(file);
    if (text === null) continue;
    const fm = parseFrontmatter(text);
    if (!fm.ok) {
      findings.push({ rule: id, file, line: 1, message: "no YAML frontmatter block found (expected a leading --- ... --- block)" });
      continue;
    }

    // Our convention (docs/extending/subagents.md): the frontmatter key is `model:`, and its
    // value is a semantic tier name from routing.json — not a literal id. A `tier:` key, if
    // ever used instead, is accepted the same way. A literal `provider/id` override is also
    // accepted, since it is strictly more specific than a tier name.
    const modelEntry = fm.entries.get("model");
    const tierEntry = fm.entries.get("tier");
    const entry = tierEntry ?? modelEntry;

    if (!entry) {
      findings.push({ rule: id, file, line: fm.startLine, message: 'frontmatter has neither "model" nor "tier" — nothing to resolve' });
      continue;
    }
    const value = entry.value;
    if (value.length === 0) {
      findings.push({ rule: id, file, line: entry.line, message: `frontmatter "${tierEntry ? "tier" : "model"}" is empty` });
      continue;
    }
    if (tierNames.has(value)) continue;
    if (PROVIDER_QUALIFIED.test(value)) continue;

    findings.push({
      rule: id,
      file,
      line: entry.line,
      message: `frontmatter "${tierEntry ? "tier" : "model"}: ${value}" resolves to neither a config/routing.json tier nor a "provider/id"`,
    });
  }
  return findings;
}
