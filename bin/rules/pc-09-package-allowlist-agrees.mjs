/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */
import { packageIdFromSettingsEntry } from "../lib/packages.mjs";

export const id = "PC-09";
export const title = "config/settings.json packages[] agrees with docs/PACKAGES.md and docs/DENYLIST.md";
export const tags = ["packages"];
export const closes = ["REQ-EXT-28", "REQ-PRV-45"];

// Both ledgers use the same table convention: an allowlist/denylist *row* is a markdown
// table row whose first cell is a backtick-quoted npm id. Per-package detail sections use
// **bold** first cells instead ("| **Pinned version** |"), so this pattern does not pick
// those up. This is a simplified reader, not a markdown parser — it is only asked to answer
// "does this id appear as a row", which the table shape makes unambiguous.
const ROW = /^\|\s*`([^`]+)`\s*\|/;

/** @param {RuleContext} ctx @param {string} relPath @returns {Set<string>} */
function readIdColumn(ctx, relPath) {
  const ids = new Set();
  for (const { text } of ctx.lines(relPath)) {
    const m = ROW.exec(text.trim());
    if (m) ids.add(m[1]);
  }
  return ids;
}

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  // config/settings.json is generated by the installer and git-ignored; on a fresh clone only
  // the tracked config/settings.default.json exists. Checking whichever is present keeps this
  // rule meaningful before the first install instead of silently returning zero findings.
  const SETTINGS = ctx.exists("config/settings.json") ? "config/settings.json" : "config/settings.default.json";
  const PACKAGES_MD = "docs/PACKAGES.md";
  if (!ctx.exists(SETTINGS)) return [];

  /** @type {Finding[]} */
  const findings = [];
  let settings;
  try {
    settings = ctx.readJSON(SETTINGS);
  } catch (err) {
    return [{ rule: id, file: SETTINGS, message: String(err.message ?? err) }];
  }

  const packages = Array.isArray(settings?.packages) ? settings.packages : [];
  if (packages.length === 0) return findings; // empty by construction — nothing to agree on

  if (!ctx.exists(PACKAGES_MD)) {
    findings.push({ rule: id, file: PACKAGES_MD, message: `settings.json declares ${packages.length} package(s) but docs/PACKAGES.md does not exist` });
    return findings;
  }

  const allowed = readIdColumn(ctx, PACKAGES_MD);
  const denied = ctx.exists("docs/DENYLIST.md") ? readIdColumn(ctx, "docs/DENYLIST.md") : new Set();

  const fileLines = ctx.lines(SETTINGS);
  for (const pkg of packages) {
    // settings.json wires packages by LOCAL PATH (`~/pi-config/node_modules/<id>`,
    // `~/pi-config/pi-packages/<id>`); the ledgers are keyed by npm id. Normalise before matching.
    const npmId = packageIdFromSettingsEntry(pkg);
    if (npmId === null) {
      findings.push({ rule: id, file: SETTINGS, message: `packages[] entry ${JSON.stringify(pkg)} has no derivable npm id — it can be matched against no ledger` });
      continue;
    }
    const needle = typeof pkg === "string" ? pkg : npmId;
    const line = fileLines.find((l) => l.text.includes(`"${needle}"`))?.line;
    if (denied.has(npmId)) {
      findings.push({ rule: id, file: SETTINGS, line, message: `package "${npmId}" is in settings.json but is rejected in docs/DENYLIST.md` });
      continue;
    }
    if (!allowed.has(npmId)) {
      findings.push({ rule: id, file: SETTINGS, line, message: `package "${npmId}" is in settings.json but has no row in docs/PACKAGES.md` });
    }
  }
  return findings;
}
