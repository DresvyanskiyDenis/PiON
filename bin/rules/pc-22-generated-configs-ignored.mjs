// bin/rules/pc-22-generated-configs-ignored.mjs — the two hand-maintained lists cannot drift.
//
// scripts/install.sh generates ten files under config/. Each one carries the answers of whoever
// ran the installer — an endpoint, a workspace host, a tenant name, a local port — so each one
// must be git-ignored, and the *tracked* artefact is its `config/<name>.default.json` template.
//
// That arrangement rests on two lists written by hand in two different files: `$GENERATED_CONFIGS`
// in scripts/install.sh, and the `config/*.json` block in .gitignore. Nothing stopped them from
// diverging, and both directions are a real defect:
//
//   - generated but NOT ignored  -> the next `git add -A` publishes somebody's endpoints. This is
//                                   the leak the .gitignore block exists to prevent.
//   - ignored but NOT generated  -> a tracked config file silently disappears from the index, and
//                                   a fresh clone is missing a file the harness needs at runtime.
//
// It cannot be a wildcard on the .gitignore side: config/ also holds a dozen tracked files the
// installer never writes (bash-timeouts.json, keybindings.json, tasks.json, the lock files...),
// and `config/*.json` would untrack every one of them.
//
// The third check is the one a reader trips over first: an ignored file must still have a shipped
// template, or a fresh clone has no way to produce it.

/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

export const id = "PC-22";
export const title = "config/*.json in .gitignore == the set scripts/install.sh generates, and every one ships a template";

const INSTALLER = "scripts/install.sh";
const GITIGNORE = ".gitignore";

// The installer's own list, as a shell string literal: GENERATED_CONFIGS="a b c".
const GENERATED_CONFIGS_RE = /^GENERATED_CONFIGS="([^"]*)"/m;

// Three files the installer writes outside that loop, because each needs bespoke logic:
// models.json is assembled per selected provider, routing.json binds tiers and egress classes,
// mcp.json is written by the MCP section and left alone when it already exists. They are named
// here rather than parsed, because there is no single shell variable to read them from — which
// would make this a THIRD list that can drift, so `run()` verifies each name is still generated
// by the installer instead of trusting this constant.
const SEPARATELY_GENERATED = ["models", "routing", "mcp"];

/** A `.gitignore` line that names one file directly under config/ — not a comment, not a negation. */
function gitignoredConfigJson(text) {
  const t = text.trim();
  if (!t || t.startsWith("#") || t.startsWith("!")) return null;
  const m = /^\/?(config\/[^/*?[\]]+\.json)$/.exec(t);
  return m ? m[1] : null;
}

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  // Not applicable rather than failing: the pi-check fixtures are bare config trees with neither
  // an installer nor a .gitignore, and a tree with no installer generates nothing to ignore.
  if (!ctx.exists(INSTALLER) || !ctx.exists(GITIGNORE)) return [];

  /** @type {Finding[]} */
  const findings = [];

  const installer = ctx.readText(INSTALLER) ?? "";
  const m = GENERATED_CONFIGS_RE.exec(installer);
  if (!m) {
    // An unknown, not a clean pass — the same stance PC-06 takes when it cannot enumerate.
    return [{
      rule: id,
      file: INSTALLER,
      message: `no GENERATED_CONFIGS="..." assignment found — this rule reads that variable to learn which config files are generated; it was renamed, split or moved, so the .gitignore block is now unchecked`,
    }];
  }

  const fromInstaller = m[1].split(/\s+/).filter(Boolean);
  for (const name of SEPARATELY_GENERATED) {
    // Keeps this file's own constant honest: if the installer stops writing one of the three, the
    // rule says so instead of quietly demanding a .gitignore line for a file nobody generates.
    if (!installer.includes(`config/${name}.json`)) {
      findings.push({
        rule: id,
        file: INSTALLER,
        message: `this rule lists "${name}" as separately generated, but ${INSTALLER} never mentions config/${name}.json — update SEPARATELY_GENERATED in bin/rules/${id.toLowerCase()}-generated-configs-ignored.mjs`,
      });
    }
  }

  const expected = new Set([...fromInstaller, ...SEPARATELY_GENERATED].map((n) => `config/${n}.json`));

  /** @type {Map<string, number>} */
  const ignored = new Map();
  for (const { line, text } of ctx.lines(GITIGNORE)) {
    const path = gitignoredConfigJson(text);
    if (path && !ignored.has(path)) ignored.set(path, line);
  }

  for (const path of [...expected].sort()) {
    if (!ignored.has(path)) {
      findings.push({
        rule: id,
        file: GITIGNORE,
        message: `${path} is generated by ${INSTALLER} but is not git-ignored — it carries the installing user's answers, so committing it publishes them; add the line to the generated-config block`,
      });
    }
  }

  for (const [path, line] of [...ignored].sort()) {
    if (!expected.has(path)) {
      findings.push({
        rule: id,
        file: GITIGNORE,
        line,
        message: `${path} is git-ignored but ${INSTALLER} does not generate it — an installer-untouched file that is meant to be tracked has been untracked; remove the line, or add the name to GENERATED_CONFIGS if the installer really does write it now`,
      });
    }
  }

  for (const path of [...expected].sort()) {
    const template = path.replace(/\.json$/, ".default.json");
    if (!ctx.exists(template)) {
      findings.push({
        rule: id,
        file: template,
        message: `${path} is generated and git-ignored, but its template ${template} is missing — a fresh clone has no way to produce ${path}`,
      });
    }
  }

  return findings;
}
