/** @typedef {import("../types.mjs").Finding} Finding */
/** @typedef {import("../types.mjs").RuleContext} RuleContext */

export const id = "PC-27";
export const title = "Every model config/models.json declares carries a complete cost block";
export const closes = [];

// PC-27 is the static half of `extensions/cost-gate`, and it exists because the runtime half can
// only fire after the money is spent.
//
// THE DEFECT, ONCE, SO THE TWO HALVES READ AS ONE RULE
//
// `cost` is required on PI's runtime model type and optional in `models.json`, and the gap is
// closed silently: the provider composer substitutes `{input:0,output:0,cacheRead:0,cacheWrite:0}`
// for any definition that omits it. After that substitution an authored zero and a forgotten field
// are the same object, so the status line reads a flat `$0.000` on a provider that may be charging
// real money. `extensions/cost-gate/authorship.ts` carries the full account.
//
// WHAT EACH HALF CAN SEE, AND WHY BOTH ARE NEEDED
//
// The gate judges a response: this model, these billed tokens, this undeclared price. That evidence
// is what makes ending the session safe, and it is also what makes the gate late. The earliest it
// can fire is the end of turn one, which on a fresh install is a session that dies before its first
// answer, having already billed for it. This rule asks the same question of the same file with no
// evidence and no consequence beyond a red line: which declared models would the composer have to
// invent a price for?
//
// WHERE IT RUNS IN THIS TREE
//
// `bin/pi-check --all` is the last thing `scripts/install.sh` does, in its "Checking the result"
// step, after `config/models.json` has been generated from the provider fragments and before the
// operator has started a session. `scripts/postinstall-verify.sh` runs it again as its `pi-check
// --all` check, which is what `scripts/update.sh` invokes at the end of an update unless
// `--no-verify` was passed. So on both paths the answer arrives before the first request rather
// than after the first bill, and re-running `bin/pi-check --all` by hand is the same answer at any
// later time.
//
// WHY A STATIC RULE IS SAFE HERE
//
// The obvious objection is that a static rule must flag every unpriced model, including the ones
// that are unpriced on purpose. It does not, because "unpriced on purpose" is not spelled as an
// omission: it is four explicit zeros, which `classifyModelCost` already calls `authored` and which
// this rule reads the same way. An omission is the only thing flagged. A zero, written down, passes
// on this rule and on the gate alike, because a decision recorded is not the defect. Silence is.
//
// A `notes[]` entry explaining an absent `cost` is not a declaration, here or at runtime. The
// provider fragments this repository ships document that spelling (see `config/providers/README.md`
// and `test/providers-cost.test.ts`, which govern the FRAGMENTS rather than the composed file this
// rule reads), and it is exactly the advice the runtime gate ends a session for. This rule fires on
// the same shape, at install time, where being wrong costs nothing.
//
// TOLERANCES
//
// No `config/models.json` means no findings: that is a tree this rule is not about, and the file is
// generated by the installer rather than tracked. A provider with no `models` array is skipped
// whole, because `modelOverrides` corrects a built-in catalogue that PI already prices and `cost`
// is not overridable there, so an omission is the only possible spelling rather than an oversight.
// Both tolerances mirror the gate's `no-opinion` verdicts, and they are the same list on purpose:
// two gates that disagree about which models are in scope would be worse than either alone.

const REL = "config/models.json";

/** The four fields of PI's `ModelCostRates`, all required, all numbers, dollars per million tokens. */
const COST_RATE_FIELDS = ["input", "output", "cacheRead", "cacheWrite"];

/**
 * Which of the four rates this `cost` value fails to state as a finite number.
 *
 * A partial `cost` counts as unpriced rather than priced: the composer's substitution is
 * whole-object, so `{ input: 2 }` replaces the default rather than merging with it, and the three
 * fields nobody wrote become the same invisible zeros as if the object were absent.
 *
 * @param {unknown} cost
 * @returns {string[]}
 */
function missingRates(cost) {
  if (cost === null || typeof cost !== "object" || Array.isArray(cost)) return [...COST_RATE_FIELDS];
  return COST_RATE_FIELDS.filter((field) => typeof cost[field] !== "number" || !Number.isFinite(cost[field]));
}

/** @param {RuleContext} ctx @returns {Finding[]} */
export function run(ctx) {
  if (!ctx.exists(REL)) return [];

  /** @type {Finding[]} */
  const findings = [];
  let models;
  try {
    models = ctx.readJSON(REL);
  } catch (err) {
    return [{ rule: id, file: REL, message: String(err.message ?? err) }];
  }

  const providers = models && typeof models === "object" ? models.providers : undefined;
  if (!providers || typeof providers !== "object") return findings;

  const fileLines = ctx.lines(REL);
  for (const [providerId, provider] of Object.entries(providers)) {
    const catalogue = provider && typeof provider === "object" ? provider.models : undefined;
    if (!Array.isArray(catalogue)) continue;
    for (const model of catalogue) {
      if (!model || typeof model !== "object" || typeof model.id !== "string") continue;
      const missing = missingRates(model.cost);
      if (missing.length === 0) continue;
      const line = fileLines.find((l) => l.text.includes(`"${model.id}"`))?.line;
      findings.push({
        rule: id,
        file: REL,
        line,
        message:
          `${providerId}/${model.id} declares no ${missing.map((f) => `cost.${f}`).join(", ")}, ` +
          `so PI substitutes zeros and every session on it reports $0.000 no matter what it charges. ` +
          `Write the rates in DOLLARS PER MILLION TOKENS, or write four explicit zeros to say that ` +
          `this endpoint is unmetered on purpose. An omission cannot say either.`,
      });
    }
  }
  return findings;
}
